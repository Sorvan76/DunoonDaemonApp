def generate_combinatorial_name() -> str:
    """Procedurally synthesizes a name using Prefix + Suffix (+ Optional Epithet)."""
    prefix = random.choice(NAME_PREFIXES)
    suffix = random.choice(NAME_SUFFIXES)
    
    # Avoid duplicate overlapping syllables (e.g. "Tor" + "or" -> "Toror")
    if prefix[-1].lower() == suffix[0].lower():
        suffix = suffix[1:]
        
    base_name = f"{prefix}{suffix}"
    
    # 25% chance to append a rich epithet
    if random.random() < 0.25:
        base_name = f"{base_name} {random.choice(TITLES_AND_EPITHETS)}"
        
    return base_name


def roll_persona(seed_keywords: str = "") -> tuple[str, str]:
    """
    Synthesizes a distinct (Agent Name, Directive Text) pair from combinatoric matrices.
    Dynamically weaves custom seed keywords into the persona matrix.
    """
    name = generate_combinatorial_name()
    role_adj = random.choice(ROLE_ADJECTIVES)
    role_noun = random.choice(ROLE_NOUNS)
    
    article = "an" if role_adj[0].lower() in "aeiou" else "a"
    role_str = f"{article} {role_adj} {role_noun}"
    
    cadence = random.choice(CADENCES)
    drive = random.choice(CORE_DRIVES)
    quirk = random.choice(VISCERAL_QUIRKS)
    
    directive = f"You are {name}, {role_str}. {cadence} {drive} {quirk}"
    
    clean_seed = seed_keywords.strip() if seed_keywords else ""
    if clean_seed and "Keywords" not in clean_seed:
        directive += f" Primary operational focus and tone modifiers: {clean_seed}."
        
    return name, directive